const VENUE_SUFFIXES = [
  "Arena",
  "Stadium",
  "Park",
  "Ground",
  "Coliseum",
];

export function venueFor(teamName: string, seedOffset: number): string {
  const index =
    Math.abs(hashString(teamName) + seedOffset) % VENUE_SUFFIXES.length;
  return `${teamName} ${VENUE_SUFFIXES[index]}`;
}

export function hashString(value: string): number {
  let hash = 2166136261;
  for (let i = 0; i < value.length; i += 1) {
    hash ^= value.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  return Math.abs(hash);
}

export function abbreviationFor(name: string): string {
  const words = name
    .replace(/[^A-Za-z0-9 ]/g, " ")
    .split(" ")
    .filter(Boolean);
  if (words.length === 1) return words[0].slice(0, 3).toUpperCase();
  return words
    .slice(0, 3)
    .map((word) => word[0])
    .join("")
    .toUpperCase();
}
